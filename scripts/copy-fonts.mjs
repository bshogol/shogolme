/* Copies the Geist weights this site uses out of @fontsource into public/fonts
 * and writes src/styles/fonts.css. The HTML preloads the latin files; latin-ext
 * is declared with a unicode-range so it only downloads when a character needs it.
 */
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "public/fonts");

const LATIN =
  "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const LATIN_EXT =
  "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF";

const faces = [
  ["Geist", 400, "@fontsource/geist", "geist-latin-400-normal.woff2", "geist-latin-ext-400-normal.woff2"],
  ["Geist", 500, "@fontsource/geist", "geist-latin-500-normal.woff2", "geist-latin-ext-500-normal.woff2"],
  ["Geist", 600, "@fontsource/geist", "geist-latin-600-normal.woff2", "geist-latin-ext-600-normal.woff2"],
  ["Geist Mono", 400, "@fontsource/geist-mono", "geist-mono-latin-400-normal.woff2", "geist-mono-latin-ext-400-normal.woff2"],
  ["Geist Mono", 500, "@fontsource/geist-mono", "geist-mono-latin-500-normal.woff2", "geist-mono-latin-ext-500-normal.woff2"],
];

mkdirSync(outDir, { recursive: true });

const rules = [
  "/* Generated by scripts/copy-fonts.mjs from @fontsource. woff2 only. */",
];

for (const [family, weight, pkg, latin, ext] of faces) {
  for (const file of [ext, latin]) {
    copyFileSync(resolve(root, "node_modules", pkg, "files", file), resolve(outDir, file));
  }
  const range = (file, unicode) => `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url("/fonts/${file}") format("woff2");
  unicode-range: ${unicode};
}`;
  // latin-ext first so the latin face wins the shared code points.
  rules.push(range(ext, LATIN_EXT), range(latin, LATIN));
}

writeFileSync(resolve(root, "src/styles/fonts.css"), `${rules.join("\n\n")}\n`);
console.log(`fonts: ${faces.length} weights`);
